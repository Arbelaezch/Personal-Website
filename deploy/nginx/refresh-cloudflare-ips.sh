#!/usr/bin/env bash
# Regenerate snippets/cloudflare-real-ip.conf from Cloudflare's published ranges.
# Run from anywhere, review the diff, commit, then ./install.sh. Cloudflare changes these rarely.
set -euo pipefail
out="$(cd "$(dirname "$0")" && pwd)/snippets/cloudflare-real-ip.conf"
{
  echo "# Recover the real client IP behind Cloudflare. Include ONLY in server blocks that are"
  echo "# proxied by Cloudflare. Only Cloudflare's ranges may set the client address, so a request"
  echo "# from anywhere else cannot spoof CF-Connecting-IP."
  echo "# Generated by refresh-cloudflare-ips.sh on $(date +%Y/%m/%d) from https://www.cloudflare.com/ips/"
  echo
  echo "# IPv4"
  curl -fsS https://www.cloudflare.com/ips-v4 | sed 's/^/set_real_ip_from /; s/$/;/'
  echo
  echo "# IPv6"
  curl -fsS https://www.cloudflare.com/ips-v6 | sed 's/^/set_real_ip_from /; s/$/;/'
  echo
  echo "real_ip_header CF-Connecting-IP;"
} > "$out"
echo "wrote $out"
